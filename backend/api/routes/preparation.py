@router.post("/plan", response_model=PreparationPlanResponse)
async def create_plan(payload: PreparationPlanRequest, user_id: str = Depends(get_current_user)):
    """
    AI generates a personalised preparation plan based on target role,
    skill gaps, current skills, past performance, and available time.
    """
    if not payload.user_id or payload.user_id == "string":
        payload.user_id = user_id

    try:
        agent = _get_agent()
        result = agent.build_recommendation(
            target_role=payload.target_role,
            skill_gaps=payload.skill_gaps or [],
            current_skills=payload.current_skills or [],
            previous_performance=payload.previous_performance or {},
            available_time=payload.available_time,
            target_job=payload.target_job,
        )
        # Map AI output → PreparationPlanResponse schema
        from backend.schemas.preparation import DailyTask
        daily_plan = [
            DailyTask(day=d.get("day", i + 1), tasks=d.get("tasks", []))
            for i, d in enumerate(result.get("daily_plan", []))
        ]
        return PreparationPlanResponse(
            user_id=payload.user_id,
            target_role=payload.target_role,
            target_job_id=payload.target_job_id,
            priority_topics=result.get("priority_topics", []),
            daily_plan=daily_plan,
            reason=result.get("reason", ""),
            estimated_time=int(result.get("estimated_time") or payload.available_time),
            practice_types=result.get("practice_types", []),
            expected_outcomes=result.get("expected_outcomes", []),
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"AI plan generation failed: {str(e)}")


